function normalizedLetters(text: string) { return [...text.toUpperCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')].slice(0, 24) }
export function glyphScale(text: string): number { return Math.min(.35, 6 / Math.max(5, normalizedLetters(text).length * 6 - 1)) }
export function glyphPoints(text: string): [number, number][] {
  const letters = normalizedLetters(text)
  const scale = glyphScale(text)
  const points: [number, number][] = []
  letters.forEach((letter, index) => {
    const rows = (ROWS[letter] ?? ROWS['?']).split('/')
    rows.forEach((row, y) => [...row].forEach((cell, x) => {
      if (cell === '1') points.push([(index * 6 + x - (letters.length * 6 - 2) / 2) * scale, (3 - y) * scale])
    }))
  })
  return points
}
